// Every available icon name (handy when choosing one)
export const ICON_NAMES = Object.keys(ICONS);

export default function Icon({ name, size = 20, strokeWidth = 2, className = '', title }) {
  const shape = ICONS[name];
  if (!shape) {
    console.warn(`Icon "${name}" does not exist. Available: ${ICON_NAMES.join(', ')}`);
    return null;
  }
  return (
    <svg
      className={`icon ${className}`.trim()}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      // Decorative icons are hidden from screen readers; icons with a title are announced
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
      focusable="false"
    >
      {title && <title>{title}</title>}
      {shape}
    </svg>
  );
}
